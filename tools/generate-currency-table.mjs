// Writes libs/shared/api-kit/src/money/iso-4217.ts from the official ISO 4217 "List One"
// (XML, published by SIX, the ISO 4217 maintenance agency). Run by hand, rarely: the table is
// part of the contract and a reviewed change (ADR-0008). The file is downloaded by the
// person running this, then passed as an argument — the script never fetches anything.
//
//   curl.exe -sSL -o list-one.xml https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml
//   node tools/generate-currency-table.mjs list-one.xml
//
// Kept: codes with a number of minor units (CcyMnrUnts is a digit), funds excluded
// (IsFund="true"). Dropped that way: metals (XAU, XAG, XPT, XPD), XDR, XXX, XTS, XSU, XUA,
// bond-market units, and fund codes (CLF, UYW, BOV, …). XAF, XOF, XPF are real currencies
// and stay (owner, 2026-11-23).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
const TARGET = 'libs/shared/api-kit/src/money/iso-4217.ts';

const [file] = process.argv.slice(2);
if (!file) {
  console.error('Usage: node tools/generate-currency-table.mjs <list-one.xml>');
  process.exit(1);
}
const bytes = readFileSync(file);
const xml = bytes.toString('utf8');
const published = xml.match(/<ISO_4217 Pblshd="(\d{4}-\d{2}-\d{2})"/)?.[1];
if (!published) throw new Error('Not an ISO 4217 list: no Pblshd date');

const field = (entry, tag) =>
  entry.match(new RegExp(`<${tag}[^>]*>([^<]*)</${tag}>`))?.[1];

const exponents = new Map();
for (const [, entry] of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const code = field(entry, 'Ccy');
  const minorUnits = field(entry, 'CcyMnrUnts');
  if (!code || !/^\d$/.test(minorUnits ?? '') || /IsFund="true"/.test(entry)) {
    continue;
  }
  const exponent = Number(minorUnits);
  // One currency in many countries: the same code must always have the same exponent.
  if (exponents.has(code) && exponents.get(code) !== exponent) {
    throw new Error(`${code}: two different exponents in the list`);
  }
  exponents.set(code, exponent);
}

const sha256 = createHash('sha256').update(bytes).digest('hex');
const rows = [...exponents]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([code, exponent]) => `  ${code}: ${exponent},`);

writeFileSync(
  TARGET,
  `// GENERATED by tools/generate-currency-table.mjs — do not edit by hand.
// Source: ISO 4217 List One, published ${published} (SIX, ISO 4217 maintenance agency)
// ${SOURCE}
// SHA-256 of the source file: ${sha256}
// ${exponents.size} currencies: every code with a number of minor units, funds excluded (ADR-0008).
// Never change the exponent of a currency that already has stored amounts.

/** Currency code → ISO 4217 exponent (digits after the decimal point). */
export const ISO_4217_EXPONENTS = {
${rows.join('\n')}
} as const satisfies Record<string, number>;
`,
);
console.log(`${TARGET}: ${exponents.size} currencies, list of ${published}`);
