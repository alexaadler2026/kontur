// Writes libs/shared/auth-server/src/password/common-passwords.ts: passwords people really
// use that are long enough to pass the length rule (15–128 characters, ADR-0010). Shorter
// ones are already refused by length, so only long ones are worth a list.
// Source: SecLists (MIT licence), Passwords/Common-Credentials. Run by hand, rarely. The
// files are downloaded by the person running this and passed as arguments — the script
// never fetches anything:
//
//   $base = 'https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials'
//   curl.exe -sSLO "$base/xato-net-10-million-passwords-1000000.txt"
//   curl.exe -sSLO "$base/Pwdb_top-1000000.txt"
//   curl.exe -sSLO "$base/100k-most-used-passwords-NCSC.txt"
//   node tools/generate-common-passwords.mjs xato-net-10-million-passwords-1000000.txt Pwdb_top-1000000.txt 100k-most-used-passwords-NCSC.txt
//
// Each entry: Unicode NFC, lower case (the check ignores case), 15–128 characters, no
// duplicates, sorted. Decisions: owner, 2026-11-23 (docs/plans/next-steps.md).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const SOURCE =
  'https://github.com/danielmiessler/SecLists/tree/master/Passwords/Common-Credentials';
const TARGET = 'libs/shared/auth-server/src/password/common-passwords.ts';
const MIN = 15;
const MAX = 128;

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error(
    'Usage: node tools/generate-common-passwords.mjs <list.txt> [<list.txt> …]',
  );
  process.exit(1);
}

const entries = new Set();
const sources = files.map((file) => {
  const bytes = readFileSync(file);
  for (const line of bytes.toString('utf8').split(/\r?\n/)) {
    const entry = line.normalize('NFC').toLowerCase();
    const length = [...entry].length; // characters (code points), not UTF-16 units
    if (length >= MIN && length <= MAX) entries.add(entry);
  }
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  return `//   ${basename(file)} — SHA-256 ${sha256}`;
});

const sorted = [...entries].sort();
const today = new Date().toISOString().slice(0, 10);

writeFileSync(
  TARGET,
  `// GENERATED by tools/generate-common-passwords.mjs — do not edit by hand.
// Source: SecLists (MIT licence), ${SOURCE}
// Downloaded ${today}:
${sources.join('\n')}
// ${sorted.length} entries: NFC, lower case, ${MIN}–${MAX} characters, no duplicates (ADR-0010).

/** Common passwords long enough to pass the length rule; compare in NFC lower case. */
export const COMMON_PASSWORDS: readonly string[] = [
${sorted.map((entry) => `  ${JSON.stringify(entry)},`).join('\n')}
];
`,
);
console.log(`${TARGET}: ${sorted.length} entries from ${files.length} lists`);
