import { ChangeDetectionStrategy, Component } from '@angular/core';
import { getHealthLiveResource } from '@adlersoft/signflow-api-client';
import { TranslocoPipe } from '@jsverse/transloco';

/**
 * One line that proves the whole chain works: signflow-api → openapi.json → generated
 * client → this screen. role="status" lets screen readers announce "checking → OK".
 */
@Component({
  selector: 'sf-api-status',
  imports: [TranslocoPipe],
  template: `
    <p role="status">
      @if (health.hasValue()) {
        {{ 'apiStatus.ok' | transloco: { version: health.value().version } }}
      } @else if (health.error()) {
        {{ 'apiStatus.error' | transloco }}
      } @else {
        {{ 'apiStatus.loading' | transloco }}
      }
    </p>
  `,
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class ApiStatus {
  /** GET /api/v1/health/live as a signal-based resource (generated by Orval). */
  protected readonly health = getHealthLiveResource();
}
